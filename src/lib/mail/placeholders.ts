/**
 * Приведение плейсхолдеров к каноническому виду `{{name}}` / `{{company}}`.
 *
 * Зачем. Движок уникальности (§5.9) понимает ровно один синтаксис переменных —
 * двойные фигурные скобки. Одиночные скобки там означают СОВСЕМ другое: это
 * spintax-альтернативы, `{привет|здравствуйте}`. Поэтому текст вида «{Имя}»
 * не ломается с ошибкой, а тихо трактуется как группа выбора из одного
 * варианта — и в письмо уходит literal «Имя» вместо имени получателя.
 * Ровно это и случилось на живой рассылке (2026-07-29).
 *
 * ИИ про наш синтаксис знать не обязан: в промпте он теперь описан, но модели
 * импровизируют, а цена ошибки — испорченные письма реальным людям. Поэтому
 * ответ модели не только просят оформить правильно, но и нормализуют здесь.
 * Тем же проходом чинится текст, набранный руками.
 *
 * Канонические формы идемпотентны: `{{name}}` остаётся `{{name}}`.
 */

/** Как посетитель мог назвать переменную → наше каноническое имя. */
const ALIASES: Record<string, string> = {
  name: "name",
  имя: "name",
  фио: "name",
  firstname: "name",
  контакт: "name",
  получатель: "name",

  company: "company",
  компания: "company",
  организация: "company",
  фирма: "company",
  companyname: "company",

  email: "email",
  почта: "email",
  mail: "email",
};

/** Ключ приводим к сравнимому виду: регистр, пробелы и разделители не важны. */
function canonical(raw: string): string | null {
  const key = raw.toLowerCase().replace(/[\s_-]/g, "");
  return ALIASES[key] ?? null;
}

function replaceWith(re: RegExp, text: string): string {
  return text.replace(re, (whole, inner: string) => {
    const key = canonical(inner);
    return key ? `{{${key}}}` : whole;
  });
}

export function normalizePlaceholders(text: string): string {
  if (!text) return text;

  let out = text;
  // Порядок важен. Сначала двойные скобки — иначе проход по одиночным залез бы
  // внутрь `{{...}}` и наплодил лишних уровней. Дальше одиночные, но только
  // те, что НЕ соседствуют с ещё одной скобкой (lookaround), и без `|` внутри:
  // группа с вертикальной чертой — это spintax, её трогать нельзя.
  out = replaceWith(/\{\{\s*([^{}|]{1,30}?)\s*\}\}/g, out);
  out = replaceWith(/(?<!\{)\{\s*([^{}|]{1,30}?)\s*\}(?!\})/g, out);
  out = replaceWith(/\[\s*([^[\]|]{1,30}?)\s*\]/g, out);
  out = replaceWith(/%\s*([^%|\s]{1,30}?)\s*%/g, out);
  return out;
}

/**
 * Косметика после подстановки переменных.
 *
 * Переменная без значения рендерится в пустую строку (у контакта может не быть
 * имени), и на её месте остаётся мусор пунктуации: «Здравствуйте, !». Подставлять
 * вместо имени что-то нейтральное («коллега») намеренно НЕ стали — для холодной
 * рассылки такое обращение само по себе выглядит как массовая рассылка. Дешевле
 * и честнее убрать следы отсутствующей подстановки.
 */
export function tidyAfterSubstitution(text: string): string {
  if (!text) return text;
  return text
    // «Здравствуйте, !» → «Здравствуйте!»  (запятая, за которой сразу знак конца)
    .replace(/([,;:])\s*([,.!?])/g, "$2")
    // пробел перед знаком препинания
    .replace(/[ \t]+([,.!?;:])/g, "$1")
    // задвоенные пробелы на месте выпавшего значения
    .replace(/[ \t]{2,}/g, " ");
}
