export function normalizeRegionCodes(values: string[] | undefined) {
  return [...new Set((values ?? []).flatMap((raw) => {
    const value = normalizeName(raw);
    if (/^\d{2}$/.test(value)) return [value];
    const code = REGION_CODES[value] ?? REGION_ALIASES[value];
    return code ? [code] : [];
  }))];
}

function normalizeName(value: string) {
  return value
    .toLocaleLowerCase("ru-RU")
    .replace(/ё/g, "е")
    .replace(/^(?:г|город)\.?\s+/i, "")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
}
